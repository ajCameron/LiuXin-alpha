@pytest.fixture
def db(pg_db):
    return pg_db[0]


def test_postgres_native_constraint_details(db):
    connection = db.driver.conn
    statements = [
        "CREATE DOMAIN feature_required AS TEXT DEFAULT 'domain book' NOT NULL",
        "CREATE DOMAIN feature_nested AS feature_required",
        "CREATE TABLE feature_parent(a INTEGER,b TEXT,PRIMARY KEY(a,b))",
        """CREATE TABLE "feature details" (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            required feature_nested,
            a INTEGER,b TEXT,
            one TEXT UNIQUE, pair_a TEXT,pair_b TEXT,
            value TEXT DEFAULT 'book', stamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            calculated BIGINT GENERATED ALWAYS AS (id+1) STORED,
            CONSTRAINT ordered_parent FOREIGN KEY(a,b) REFERENCES feature_parent(a,b)
                ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
            UNIQUE(pair_a,pair_b))""",
        'CREATE UNIQUE INDEX feature_partial ON "feature details"(b) WHERE b IS NOT NULL',
        'CREATE UNIQUE INDEX feature_expression ON "feature details"(lower(one))',
        'CREATE UNIQUE INDEX feature_included ON "feature details"(pair_a) INCLUDE (pair_b)',
    ]
    for statement in statements:
        connection.execute(statement).close()
    spec = db.driver_wrapper.get_table_spec("feature details", connection=connection)
    columns = {column.name: column for column in spec.columns}
    assert columns["id"].identity and columns["id"].nullable is False
    assert columns["required"].nullable is False
    assert (
        columns["required"].has_default
        and "domain book" in columns["required"].default_sql
    )
    assert columns["value"].has_default and "book" in columns["value"].default_sql
    assert columns["calculated"].generated and not columns["calculated"].has_default
    assert columns["one"].is_unique and columns["pair_a"].is_unique
    assert not columns["pair_b"].is_unique and not columns["b"].is_unique
    fk = spec.foreign_keys[0]
    assert fk.columns == ("a", "b") and fk.references_columns == ("a", "b")
    assert fk.references_schema == db.driver.schema
    assert fk.deferrable and fk.initially_deferred and fk.on_delete == "CASCADE"
    included = next(index for index in spec.indexes if index.name == "feature_included")
    assert included.columns == ("pair_a",) and included.included_columns == ("pair_b",)
    assert next(
        index for index in spec.indexes if index.name == "feature_expression"
    ).columns == (None,)
    assert next(
        index for index in spec.indexes if index.name == "feature_partial"
    ).predicate
    connection.rollback()
