"""Check direct-write durability and identity policy on real PostgreSQL."""

from __future__ import annotations

import os
from contextlib import closing
from copy import deepcopy
from uuid import uuid4

import pytest

from LiuXin_alpha.databases.database import Database
from LiuXin_alpha.databases.database_driver_plugins.PostgreSQL.connection import (
    connect_postgres,
)
from LiuXin_alpha.errors import DatabaseDriverError


@pytest.fixture
def pg_db():
    """Own a disposable schema; inspect commits using an independent connection."""
    url = os.environ.get("LIUXIN_TEST_POSTGRES_URL", "").strip()
    if not url:
        pytest.skip("LIUXIN_TEST_POSTGRES_URL is not configured.")
    metadata = {"postgres_url": url, "schema": f"liuxin_row_writes_{uuid4().hex}"}
    with closing(connect_postgres(metadata, prompt_for_password=False)) as reader:
        db = None
        try:
            db = Database(
                metadata=metadata,
                db_type="PostgreSQL",
                create=True,
                repair_bootstrap_rows=False,
                enable_storage_manager=False,
                enable_maintenance=False,
            )
            with db.driver.conn:
                db.driver.conn.execute(
                    "CREATE TABLE review_items ("
                    "review_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    "review_item_text TEXT UNIQUE, review_item_other TEXT)"
                )
                db.driver.conn.execute(
                    "CREATE TABLE review_references ("
                    "review_reference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    "review_reference_item BIGINT REFERENCES review_items(review_item_id))"
                )
            yield db, reader
        finally:
            if db is not None:
                db.close()
            reader.rollback()
            with reader:
                with reader.cursor() as cursor:
                    cursor.execute(
                        f'DROP SCHEMA IF EXISTS "{metadata["schema"]}" CASCADE'
                    )


def stored(pg_db, table, columns, order_by, where="", params=()):
    """Observe only durable state, outside the facade's primary transaction."""
    db, reader = pg_db
    reader.rollback()
    with reader.cursor() as cursor:
        cursor.execute(
            f'SELECT {columns} FROM "{db.driver.schema}"."{table}" '
            f"{where} ORDER BY {order_by}",
            params,
        )
        return cursor.fetchall()


def test_postgres_bulk_insert_preserves_mapping_order_and_inputs(pg_db):
    """Differently ordered dictionaries bind values to their own named columns."""
    db, _ = pg_db
    rows = [
        {
            "table": "review_items",
            "review_item_text": "first",
            "review_item_other": "one",
        },
        {"review_item_other": "two", "review_item_text": "second"},
    ]
    original = deepcopy(rows)
    db.driver_wrapper.add_multiple_rows(rows)
    assert stored(
        pg_db, "review_items", "review_item_text, review_item_other", "review_item_id"
    ) == [
        ("first", "one"),
        ("second", "two"),
    ]
    assert rows == original


def test_postgres_failed_bulk_insert_rolls_back_earlier_rows(pg_db):
    """A late constraint violation cannot publish the successful prefix."""
    import psycopg2

    db, _ = pg_db
    with pytest.raises(DatabaseDriverError) as caught:
        db.driver_wrapper.add_multiple_rows(
            [
                {"review_item_text": "duplicate"},
                {"review_item_text": "duplicate"},
            ]
        )
    assert isinstance(caught.value.__cause__, psycopg2.IntegrityError)
    assert stored(pg_db, "review_items", "*", "review_item_id") == []
    db.driver_wrapper.add_row({"review_item_text": "after failure"})
    assert stored(pg_db, "review_items", "review_item_text", "review_item_id") == [
        ("after failure",)
    ]


def test_postgres_failed_bulk_update_rolls_back_earlier_rows(pg_db):
    """A later unique-value conflict restores earlier updates and leaves SQL usable."""
    import psycopg2

    db, _ = pg_db
    db.driver_wrapper.add_multiple_rows(
        [
            {"review_item_text": "first"},
            {"review_item_text": "second"},
        ]
    )
    original = stored(pg_db, "review_items", "*", "review_item_id")
    with pytest.raises(psycopg2.IntegrityError):
        db.driver_wrapper.update_columns(
            {row[0]: "duplicate" for row in original}, field="review_item_text"
        )
    assert stored(pg_db, "review_items", "*", "review_item_id") == original
    db.driver_wrapper.update_columns(
        {original[0][0]: "recovered"}, field="review_item_text"
    )


@pytest.mark.parametrize("route", ["ids", "values"])
def test_postgres_failed_bulk_delete_preserves_rows_and_cause(pg_db, route):
    """Both delete entry points retain every row after a foreign-key failure."""
    import psycopg2

    db, _ = pg_db
    db.driver_wrapper.add_multiple_rows(
        [
            {"review_item_text": "first"},
            {"review_item_text": "second"},
        ]
    )
    original = stored(pg_db, "review_items", "*", "review_item_id")
    ids = [row[0] for row in original]
    db.driver_wrapper.add_row({"review_reference_item": ids[1]})
    with pytest.raises(DatabaseDriverError) as caught:
        if route == "ids":
            db.driver_wrapper.delete_by_id("review_items", ids)
        else:
            db.driver_wrapper.delete("review_items", "review_item_id", ids)
    assert isinstance(caught.value.__cause__, psycopg2.IntegrityError)
    assert stored(pg_db, "review_items", "*", "review_item_id") == original


def test_postgres_unchanged_row_sync_preserves_literal_none(pg_db):
    """The Row path keeps literal text distinct from SQL NULL on PostgreSQL."""
    db, _ = pg_db
    row_id = db.macros.insert_row("works", {"work_title": "None"})
    row = db.get_row_from_id("works", row_id)
    row.sync()
    assert stored(pg_db, "works", "work_title", "work_id") == [("None",)]
    row["work_title"] = None
    row.sync()
    assert stored(pg_db, "works", "work_title", "work_id") == [(None,)]


@pytest.mark.parametrize("route", ["row_dict", "columns"])
def test_postgres_identity_only_update_keeps_derived_key_and_uniqueness(pg_db, route):
    """Both direct update paths derive an omitted display field on their connection."""
    import psycopg2

    db, _ = pg_db
    row_id = db.macros.insert_row("tags", {"tag": "Space Opera"})
    if route == "row_dict":
        db.driver_wrapper.update_row({"tag_id": row_id, "tag_phash": "wrong"})
    else:
        db.driver_wrapper.update_columns({row_id: "wrong"}, field="tag_phash")
    assert stored(pg_db, "tags", "tag, tag_phash", "tag_id") == [
        ("Space Opera", "space opera")
    ]
    with pytest.raises(psycopg2.IntegrityError):
        db.macros.insert_row("tags", {"tag": "SPACE OPERA"})
