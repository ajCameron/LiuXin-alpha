    def _set_creator_from_normed_key(self, creator_key, value, update: bool = False):
        """
        Store creator values under an already normalized role.

        None is ignored. Existing stores accept strings/lists/tuples through the filtered
        helper; dictionaries replace by reference unless update is true. Unsupported value
        types produce NotImplementedError. A missing role is created and receives the
        supplied value as one mapping key.

        Example:
            Exercise the owning behavior with pytest::

                python -m pytest -q tests/metadata/containers/calibre_like_book_metadata/test_metadata_creators.py


        :param creator_key: Normalized creator-role key or None for a no-op.
        :param value: Name, list/tuple of names, name-to-row mapping, or None.
        :param update: Whether dictionary input updates the existing role store instead of
            replacing it.
        :return: None.
        """
        _data = object.__getattribute__(self, "_data")

        if creator_key is not None:

            if value is None:
                return

            if creator_key in _data:

                if isinstance(value, six_string_types) or isinstance(value, (tuple, list)):

                    self._set_creator_from_str_iterable_none(creator_key, value)

                elif isinstance(value, dict):

                    if not update:
                        _data[creator_key] = value
                    else:
                        _data[creator_key].update(value)

                else:
                    raise NotImplementedError("value type not recognized - type(value): {}".format(type(value)))
                return

            elif creator_key not in _data:
                _data[creator_key] = OrderedDict()
                _data[creator_key][value] = None
                return

            else:
                raise NotImplementedError("This position should never be reached")

    def _set_creator_from_str_iterable_none(self, creator_key, value):
        """
        Add names to an existing role store, dropping autogenerated-name matches.

        Strings are parsed through string_to_authors; list/tuple entries are used directly.
        Added names receive None row ids, replacing prior ids for matching names. None or an
        absent role does nothing.

        Example:
            Exercise the owning behavior with pytest::

                python -m pytest -q tests/metadata/containers/calibre_like_book_metadata/test_metadata_creators.py


        :param creator_key: Existing normalized role key.
        :param value: Author string, tuple/list of names, or None.
        :return: None.
        """
        _data = object.__getattribute__(self, "_data")

        if creator_key in _data:

            if isinstance(value, six_string_types):

                # Check to see if the passed values is one of those that should be ignored
                for creator_re in CREATOR_DROP_REGEX_SET:
                    if re.match(creator_re, value):
                        return

                for author in string_to_authors(value):
                    _data[creator_key][author] = None

            elif isinstance(value, (tuple, list)):
                for v in value:
                    # Filter out the values of v which are in the autogenerated drop regex list
                    try:
                        for creator_re in CREATOR_DROP_REGEX_SET:
                            if re.match(creator_re, v):
                                raise AutogeneratedCreator
                    except AutogeneratedCreator:
                        continue
                    else:
                        _data[creator_key][v] = None

            elif value is None:
                pass

            else:
                raise NotImplementedError("value type not recognized - type(value): {}".format(type(value)))

