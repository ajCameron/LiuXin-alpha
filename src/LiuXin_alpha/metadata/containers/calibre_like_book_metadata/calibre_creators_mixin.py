class AutogeneratedCreator(Exception):
    """
    Signal an autogenerated creator name so insertion loops can skip it.

    This internal control-flow exception is caught by creator helpers after a
    drop-pattern match.

    Example:
        Exercise the owning behavior with pytest::

            python -m pytest -q tests/metadata/containers/calibre_like_book_metadata/test_metadata_creators.py
    """
    pass



class CreatorsMethodsMixin:
    """
    Provide grouped creator views and insertion helpers over role-specific _data mappings.

    Example:
        Exercise the owning behavior with pytest::

            python -m pytest -q tests/metadata/containers/calibre_like_book_metadata/test_metadata_creators.py
    """

    @property
    def creators(self) -> dict[str, list[str]]:
        """
        Copy role-to-name lists from the recognized creator stores.

        Include empty stores but omit roles absent from _data; database row values are not
        exposed.

        Example:
            >>> from LiuXin_alpha.metadata.containers.calibre_like_book_metadata import CalibreLikeLiuXinBookMetaData
            >>> book = CalibreLikeLiuXinBookMetaData()
            >>> book.authors = ['Writer']
            >>> book.creators['authors']
            ['Writer']


        :return: New dictionary of independent name lists.
        """
        _data = object.__getattribute__(self, "_data")

        # All creators are requested - build the directory and return it
        creators_dict = dict()
        for creator_role in CREATOR_CATEGORIES:
            if creator_role in _data:
                creators_dict[creator_role] = deepcopy([creator for creator in _data[creator_role].keys()])
        return creators_dict

    def get_authors_copy(self):
        """
        Copy author names in their stored order, without database row information.

        Example:
            >>> from LiuXin_alpha.metadata.containers.calibre_like_book_metadata import CalibreLikeLiuXinBookMetaData
            >>> book = CalibreLikeLiuXinBookMetaData()
            >>> book.authors = ['Writer']
            >>> names = book.get_authors_copy()
            >>> names.append('Other')
            >>> book.get_authors_copy()
            ['Writer']


        :return: Independent author-name list, or an empty list when no author store exists.
        """
        _data = object.__getattribute__(self, "_data")
        if "authors" in _data:
            author_list = [a for a in _data["authors"].keys()]
            return deepcopy(author_list)
        return []

    def get_creators_dump(self):
        """
        Deep-copy each recognized creator-role mapping, including row/id values.

        Example:
            Exercise the owning behavior with pytest::

                python -m pytest -q tests/metadata/containers/calibre_like_book_metadata/test_metadata_creators.py


        :return: Role-to-copied-mapping dictionary.
        """
        _data = object.__getattribute__(self, "_data")
        creators_dict = dict()
        for creator_role in CREATOR_CATEGORIES:
            if creator_role in _data:
                creators_dict[creator_role] = deepcopy(_data[creator_role])
        return creators_dict

    def add_creators(self, creators):
        """
        Normalize role aliases and add copied creator names, skipping autogenerated string entries.

        String input attempts encoding/BOM cleanup and splits ampersand-separated authors. A
        single string without ampersands is inserted and returns from the whole method, so
        later roles are not processed. Iterable entries are converted to text without that
        string-only filtering. Unknown roles produce InputIntegrityError.

        Example:
            Exercise the owning behavior with pytest::

                python -m pytest -q tests/metadata/containers/calibre_like_book_metadata/test_metadata_creators.py


        :param creators: Role-to-name-or-iterable mapping; copied before processing.
        :return: None.
        """
        _data = object.__getattribute__(self, "_data")
        creators = deepcopy(creators)

        for creator_role in creators:

            value = creators[creator_role]
            s_creator_role = standardize_creator_category(creator_role)

            if s_creator_role is None:
                err_str = "creator_role was standardized to None - so the creator couldn't be parsed"
                err_str = default_log.log_variables(err_str, "ERROR", ("creator_role", creator_role), ("value", value))
                raise InputIntegrityError(err_str)

            try:
                if isinstance(value, six_string_types):
                    # Try detecting the encoding and then re-encoding the string with that encoding
                    try:
                        value_encoding = force_encoding(value, verbose=False)
                        value = six_unicode(value, encoding=value_encoding)
                    except UnicodeDecodeError:
                        value = six_unicode(value, errors="ignore")
                    except TypeError:
                        # If the string is already unicode then just leave it
                        pass

                    # Remove any byte order marks that remain from the encoding guess - snip the first character
                    if value.startswith("\ufeff"):
                        value = value[1:]

                    # Filter for auto generated additions to the creators - abort if the creator is autogenerated
                    for creator_re in CREATOR_DROP_REGEX_SET:
                        if re.match(creator_re, value):
                            raise AutogeneratedCreator

                    # If & is present assume that we have a single creator
                    if "&" not in value:
                        if s_creator_role not in _data:
                            _data[s_creator_role] = OrderedDict()
                        if value not in _data[s_creator_role]:
                            _data[s_creator_role][value] = None
                        return
                    else:
                        value = string_to_authors(value)
                        value = [creator.strip() for creator in value]

                if s_creator_role not in _data:
                    _data[s_creator_role] = OrderedDict()
                for creator_name in value:
                    creator_name = six_unicode(creator_name)
                    if creator_name not in _data[s_creator_role]:
                        _data[s_creator_role][creator_name] = None

            except AutogeneratedCreator:
                continue

    def update_creators(self, creators_dict):
        """
        Update existing role mappings directly with name-to-row pairs.

        Role names must already be normalized and present. Mapped values are retained by
        reference, and missing roles produce KeyError.

        Example:
            Exercise the owning behavior with pytest::

                python -m pytest -q tests/metadata/containers/calibre_like_book_metadata/test_metadata_creators.py


        :param creators_dict: Mapping of existing role names to name-to-row/id mappings.
        :return: None.
        """
        _data = object.__getattribute__(self, "_data")

        # Iterate through, updating all the creators
        for creator_role in creators_dict:
            _data[creator_role].update(creators_dict[creator_role])

    def read_creators(self, creators_dict):
        """
        Assign each role value through the owner's __setattr__ normalization path.

        Example:
            Exercise the owning behavior with pytest::

                python -m pytest -q tests/metadata/containers/calibre_like_book_metadata/test_metadata_creators.py


        :param creators_dict: Role-to-name-or-name-sequence mapping to read.
        :return: None.
        """
        for creator_role in creators_dict:
            self.__setattr__(creator_role, creators_dict[creator_role])

