"""Canonical public WEMI container API surface.

Placement rule:
Core WEMI entity APIs, WEMI-attached metadata-family APIs, and agent
identity/profile/participation APIs all live here.

Semantic rule:
Sharing a package home does not make these families the same kind of object.
Within this package we still distinguish between core WEMI identity objects,
core WEMI metadata bundles, additional metadata families, the agent-profile
exception, and read-side snapshots/views/slices.

Runtime-installed convenience properties are an accepted temporary ergonomic
layer in some families. They are convenience sugar, not the canonical core API.
"""

