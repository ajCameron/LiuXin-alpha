"""Render native Catalog relationship DDL from the shared FRBR declarations."""

from __future__ import annotations

import tomllib
from collections.abc import Mapping
from pathlib import Path

from LiuXin_alpha.databases.database_driver_plugins.PostgreSQL.link_ddl import (
    _link_constraints,
    _link_extra_columns,
    _pg_literal,
    _q,
)


def catalog_link_statements(
    tables: Mapping[str, tuple[str, ...]], root: Path
) -> tuple[str, ...]:
    """Create declared links between the supplied Catalog tables, including role registries.

    Table names and columns come from the bundled schema catalog. Source/target
    direction comes from TOML; physical names follow sorted column prefixes.
    Foreign keys, cardinality and type checks are enforced by PostgreSQL.
    """
    requests = tomllib.loads((root / "interlink_table_requests.toml").read_text())
    statements: list[str] = []
    for request in requests["interlinks"]:
        left_table, right_table = request["left_table"], request["right_table"]
        if left_table not in tables or right_table not in tables:
            continue
        left_id, right_id = tables[left_table][0], tables[right_table][0]
        left_base, right_base = (
            left_id.removesuffix("_id"),
            right_id.removesuffix("_id"),
        )
        kind = request.get("link_type", "many_to_many").replace("_to_", "_")
        if left_base > right_base:
            left_table, right_table = right_table, left_table
            left_id, right_id = right_id, left_id
            left_base, right_base = right_base, left_base
            kind = {"one_many": "many_one", "many_one": "one_many"}.get(kind, kind)
        base = f"{left_base}_{right_base}_link"
        table = f"{base}s"
        left_fk, right_fk = f"{base}_{left_base}_id", f"{base}_{right_base}_id"
        nullable = "null" if request.get("nullable", True) else "not null"
        requested = set(request.get("requested_columns", ()))
        columns = [
            f"{_q(base + '_id')} bigint generated by default as identity primary key",
            f"{_q(left_fk)} bigint {nullable} references {_q(left_table)} ({_q(left_id)}) on delete cascade",
            f"{_q(right_fk)} bigint {nullable} references {_q(right_table)} ({_q(right_id)}) on delete cascade",
            *(column for _suffix, column in _link_extra_columns(base, requested)),
            *_link_constraints(
                link_type=kind,
                link_base=base,
                left_base=left_base,
                right_base=right_base,
                left_fk_col=left_fk,
                right_fk_col=right_fk,
                has_type="type" in requested,
                has_priority="priority" in requested,
            ),
        ]
        types: list[str] = []
        for value in request.get("types", ()):
            if value == "insert_marc_roles":
                from LiuXin_alpha.constants.marc_relator_dicts import MARC_ROLE_DESC

                types.extend(sorted(MARC_ROLE_DESC))
            else:
                types.append(value)
        if types and "type" in requested:
            type_table = table + "__types"
            statements.append(
                f'create table if not exists {_q(type_table)} ("type" text primary key)'
            )
            statements.extend(
                f'insert into {_q(type_table)} ("type") values ({_pg_literal(value)}) on conflict do nothing'
                for value in dict.fromkeys(types)
            )
            columns.append(
                f'foreign key ({_q(base + "_type")}) references {_q(type_table)} ("type")'
            )
        statements.append(
            f"create table if not exists {_q(table)} (\n  "
            + ",\n  ".join(columns)
            + "\n)"
        )
        for column in (left_fk, right_fk):
            statements.append(
                f"create index if not exists {_q(column + '_idx')} on {_q(table)} ({_q(column)})"
            )
    statements.extend(_intralink_statements(tables, root))
    return tuple(statements)


def _intralink_statements(
    tables: Mapping[str, tuple[str, ...]], root: Path
) -> list[str]:
    """Render current self-relations with type, symmetry and endpoint constraints."""
    requests = tomllib.loads((root / "intralink_table_requests.toml").read_text())
    statements: list[str] = []
    for request in requests["intralinks"]:
        target = request["table"]
        if target not in tables:
            continue
        target_id = tables[target][0]
        stem = target_id.removesuffix("_id")
        base = f"{stem}_{stem}_intralink"
        table = base + "s"
        primary, secondary = base + "_primary_id", base + "_secondary_id"
        requested = set(request.get("requested_cols", ()))
        columns = [
            f"{_q(base + '_id')} bigint generated by default as identity primary key",
            *(
                f"{_q(column)} bigint not null references {_q(target)} ({_q(target_id)}) on delete cascade"
                for column in (primary, secondary)
            ),
            *(column for _suffix, column in _link_extra_columns(base, requested)),
            f"check ({_q(primary)} <> {_q(secondary)})",
        ]
        identity = [primary, secondary]
        if "type" in requested:
            identity.append(base + "_type")
        columns.append("unique (" + ", ".join(_q(column) for column in identity) + ")")
        types = request.get("types", ())
        if types and "type" in requested:
            type_table = table + "__types"
            statements.append(
                f'create table if not exists {_q(type_table)} ("type" text primary key)'
            )
            statements.extend(
                f'insert into {_q(type_table)} ("type") values ({_pg_literal(value)}) on conflict do nothing'
                for value in types
            )
            columns.append(
                f'foreign key ({_q(base + "_type")}) references {_q(type_table)} ("type")'
            )
            symmetric = request.get("symmetric_types", ())
            if symmetric:
                labels = ", ".join(_pg_literal(value) for value in symmetric)
                columns.append(
                    f"check ({_q(base + '_type')} not in ({labels}) or {_q(primary)} < {_q(secondary)})"
                )
        statements.append(
            f"create table if not exists {_q(table)} (\n  "
            + ",\n  ".join(columns)
            + "\n)"
        )
    return statements


def hierarchy_guard_statements() -> tuple[str, ...]:
    """Enforce parent-cycle rejection for Catalog hierarchy rows on PostgreSQL."""
    statements: list[str] = []
    for table, stem in (
        ("genres", "genre"),
        ("subjects", "subject"),
        ("series", "series"),
    ):
        row_id, parent = _q(stem + "_id"), _q(stem + "_parent_id")
        function = _q(stem + "_parent_cycle_guard")
        statements.append(f"""
            create or replace function {function}() returns trigger language plpgsql as $guard$
            begin
                if new.{parent} is not null and exists (
                    with recursive ancestors(id) as (
                        select new.{parent}
                        union
                        select node.{parent} from {_q(table)} node
                        join ancestors on node.{row_id} = ancestors.id
                        where node.{parent} is not null
                    ) select 1 from ancestors where id = new.{row_id}
                ) then
                    raise exception 'parent relationship would create a cycle' using errcode = '23514';
                end if;
                return new;
            end $guard$
        """)
        statements.append(f"drop trigger if exists {function} on {_q(table)}")
        statements.append(
            f"create trigger {function} before insert or update of {parent} on {_q(table)} "
            f"for each row execute function {function}()"
        )
    return tuple(statements)
